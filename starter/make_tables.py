"""Collect every runs/*/results.json into the tables your report needs.

    python starter/make_tables.py

Writes report/tables.md plus one CSV per question. Paste the tables into your report and
then write the analysis - the tables are not the analysis, they are the evidence for it.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "runs"
OUT_DIR = ROOT / "report"

VIEWS = {
    "q1": ["detector", "weights", "zero_shot", "epochs", "mAP50", "mAP50_95",
           "mAP_small", "mAP_large", "inference_ms_per_image", "fps", "total_params",
           "train_minutes"],
    "q2": ["tag", "model", "encoder", "encoder_weights", "frozen_encoder", "loss",
           "best_mIoU", "best_mDice", "pixel_accuracy", "trainable_params", "train_minutes"],
    "q3": ["cell", "max_len", "hidden_size", "bidirectional", "readout", "clip_grad",
           "best_test_acc", "final_train_acc", "total_params", "recurrent_params",
           "train_minutes"],
}

TITLES = [
    ("q1", "Q1 - object detection: YOLOv8 vs Faster R-CNN"),
    ("q2", "Q2 - semantic segmentation"),
    ("q3", "Q3 - recurrent networks: RNN vs LSTM vs GRU"),
]


def load(question: str) -> pd.DataFrame:
    path = RUNS / question / "results.json"
    if not path.exists():
        return pd.DataFrame()
    rows = json.loads(path.read_text(encoding="utf-8"))
    df = pd.DataFrame(rows)

    # Q1 records latency either inline (YOLO) or in an 'inference' dict (Faster R-CNN).
    if question == "q1" and "inference" in df.columns:
        df["inference_ms_per_image"] = df.apply(
            lambda r: (r["inference"] or {}).get("latency_ms")
            if isinstance(r.get("inference"), dict) else r.get("inference_ms_per_image"),
            axis=1)
        df["fps"] = df.apply(
            lambda r: (r["inference"] or {}).get("fps")
            if isinstance(r.get("inference"), dict) else r.get("fps"), axis=1)

    cols = [c for c in VIEWS[question] if c in df.columns]
    return df[cols] if cols else df


def main() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    chunks = ["# Results tables\n",
              "Generated by starter/make_tables.py - do not hand-edit, re-run it instead.\n"]
    found = False

    for question, title in TITLES:
        df = load(question)
        if df.empty:
            chunks.append("\n## {}\n\n_no runs recorded yet_\n".format(title))
            continue
        found = True
        df.to_csv(OUT_DIR / "{}_results.csv".format(question), index=False)
        chunks.append("\n## {}\n\n".format(title))
        chunks.append(df.to_markdown(index=False))
        chunks.append("\n")

    (OUT_DIR / "tables.md").write_text("".join(chunks), encoding="utf-8")
    print("[written] {}".format(OUT_DIR / "tables.md"))
    if not found:
        print("No results found yet - run the starters under starter/ first.")
        return 0
    print("\n".join("".join(chunks).splitlines()[:60]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
